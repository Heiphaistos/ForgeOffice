import { killChrome, start, key, sleep, ok, shot, done } from './lib.mjs';
killChrome(); const b = await start('pdf', 'pdf', 'essai.pdf');
const click = async (x, y) => { await b.send('Input.dispatchMouseEvent', { type: 'mousePressed', x, y, button: 'left', clickCount: 1 }); await b.send('Input.dispatchMouseEvent', { type: 'mouseReleased', x, y, button: 'left', clickCount: 1 }); await sleep(400); };
const cards = () => b.ev(`[...document.querySelectorAll('.pdf-comment')].map((c) => c.textContent.replace(/\s+/g, ' ').trim())`);
try {
  await sleep(800);
  await b.click('text=Commentaire'); await sleep(400);
  await b.clickText('button', 'Note');
  await click(700, 400);
  await b.press('Alpha note');
  await b.clickText('button', 'Note');
  await click(900, 600);
  await b.press('Beta rappel');
  await b.clickText('button', 'Rectangle');
  await b.send('Input.dispatchMouseEvent', { type: 'mousePressed', x: 600, y: 700, button: 'left', clickCount: 1 });
  await b.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 750, y: 780, button: 'left' });
  await b.send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: 750, y: 780, button: 'left', clickCount: 1 });
  await sleep(500);
  await b.click('.pdf-rail__btn[aria-label="Commentaires"]'); await sleep(600);
  const all = await cards();
  console.log(JSON.stringify(all)); await shot(b, 'comments-dbg');
  ok('3 commentaires listés', all.length === 3, String(all.length));
  await shot(b, 'comments-all');
  await b.ev(`(() => { const i = document.querySelector('.pdf-comments__filter input'); i.focus(); })()`);
  await b.press('alpha'); await sleep(400);
  const f1 = await cards();
  ok('filtre texte « alpha » : 1 commentaire', f1.length === 1 && /Alpha/.test(f1[0]), JSON.stringify(f1));
  await shot(b, 'comments-text');
  await b.ev(`(() => { const i = document.querySelector('.pdf-comments__filter input'); i.select(); })()`);
  await key(b, 'Backspace');
  await b.ev(`(() => { const s = document.querySelectorAll('.pdf-comments__filter select')[0]; s.value = 'shape'; s.dispatchEvent(new Event('change', { bubbles: true })); })()`); await sleep(400);
  const f2 = await cards();
  ok('filtre type « Forme » : 1 commentaire', f2.length === 1 && /Forme/.test(f2[0]), JSON.stringify(f2));
  ok('compteur « 1 sur 3 »', (await b.ev(`document.querySelector('.pdf-comments__filter').textContent`)).includes('1 sur 3'));
  await b.clickText('button', 'Effacer le filtre'); await sleep(300);
  ok('filtre effacé : 3', (await cards()).length === 3);
  await shot(b, 'comments-type');
} catch (e) { console.log('ERREUR', e); }
await done(b); process.exit(0);
